// Embeds pdf.js (v3, UMD build) into a TS module so the drawing viewer works fully offline.
// Run: node scripts/build-engine.js   (re-run after upgrading pdfjs-dist)
const fs = require('fs');
const path = require('path');

const dir = path.join(__dirname, '..', 'node_modules', 'pdfjs-dist', 'build');
const lib = fs.readFileSync(path.join(dir, 'pdf.min.js'), 'utf8');
const worker = fs.readFileSync(path.join(dir, 'pdf.worker.min.js'), 'utf8');
const out = path.join(__dirname, '..', 'src', 'engine', 'pdfjsSource.ts');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(
  out,
  '/* eslint-disable */\n// GENERATED by scripts/build-engine.js — do not edit.\n' +
    `export const PDFJS_LIB = ${JSON.stringify(lib)};\n` +
    `export const PDFJS_WORKER = ${JSON.stringify(worker)};\n`,
);
console.log('wrote', out, Math.round(fs.statSync(out).size / 1024), 'KB');
